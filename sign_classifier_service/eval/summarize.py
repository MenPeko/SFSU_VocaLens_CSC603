"""Write docs/SIGN_RESULTS.md from the run folders under data/sign-reports/eval/.

Only aggregate numbers go into the committed file: no clip names, session
IDs, signer IDs, landmarks, or weights.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any, Optional

from ..classifier import CORE_SIGN_LABELS
from . import REPORTS_DIR, RESULTS_DOC_PATH, read_json
from .run import ASL_TEST, OWN_TEST, TEAM_TEST

CITATION = (
    "ASL Citizen: Desai et al. 2023, \"ASL Citizen: A Community-Sourced Dataset for Advancing Isolated "
    "Sign Language Recognition\" (`desai2023asl` in `docs/DATA_LICENSES.md`)."
)


def load_runs(reports_dir: Path) -> list[dict[str, Any]]:
    runs = [read_json(path) for path in sorted(reports_dir.glob("*/metrics.json"))]
    return sorted(runs, key=lambda run: run["createdAt"])


def _accuracy_cell(result: Optional[dict[str, Any]]) -> str:
    if not result or result.get("accuracy") is None:
        return "n/a"
    interval = result.get("accuracy95")
    suffix = f" ({interval[0]:.3f}-{interval[1]:.3f})" if interval else ""
    return f"{result['accuracy']:.3f}{suffix}, n={result['clips']}"


def render(runs: list[dict[str, Any]]) -> str:
    lines = [
        "# Sign classifier results",
        "",
        "Generated by `python -m sign_classifier_service.eval.summarize` from local run folders. "
        "Method: `docs/SIGN_EVAL_PLAN.md`. Aggregate numbers only.",
        "",
        "A dataset is kept only if accuracy on own held-out recordings is higher than in the run it extends. "
        "Accuracy is shown with a 95% bootstrap interval and the clip count.",
        "",
    ]
    if not runs:
        lines += ["No runs have been recorded yet.", ""]
        return "\n".join(lines)

    lines += [
        "| Run | Date | Training sources | Seed | Training clips | Own held-out | ASL Citizen held-out | Team | Decision |",
        "| --- | --- | --- | ---: | ---: | --- | --- | --- | --- |",
    ]
    for run in runs:
        tests = run["testSets"]
        lines.append(
            "| {name} | {date} | {sources} | {seed} | {clips} | {own} | {asl} | {team} | {decision} |".format(
                name=run["experiment"],
                date=run["createdAt"][:10],
                sources=", ".join(run["trainSources"]),
                seed=run["seed"],
                clips=run["trainClips"],
                own=_accuracy_cell(tests.get(OWN_TEST)),
                asl=_accuracy_cell(tests.get(ASL_TEST)),
                team=_accuracy_cell(tests.get(TEAM_TEST)),
                decision=run["decision"]["decision"],
            )
        )

    lines += ["", "## Per-sign accuracy on own held-out recordings", ""]
    lines.append("| Run | " + " | ".join(CORE_SIGN_LABELS) + " |")
    lines.append("| --- |" + " ---: |" * len(CORE_SIGN_LABELS))
    for run in runs:
        own = run["testSets"].get(OWN_TEST)
        if not own:
            continue
        cells = []
        for label in CORE_SIGN_LABELS:
            row = own["perSign"][label]
            cells.append(f"{row['accuracy']:.2f} ({row['support']})" if row["accuracy"] is not None else "n/a")
        lines.append(f"| {run['experiment']} {run['createdAt'][:10]} | " + " | ".join(cells) + " |")

    lines += ["", "## Training clips per sign", ""]
    lines.append("| Run | " + " | ".join(CORE_SIGN_LABELS) + " | Largest/smallest |")
    lines.append("| --- |" + " ---: |" * (len(CORE_SIGN_LABELS) + 1))
    for run in runs:
        counts = run["trainCounts"]
        ratio = counts.get("largestToSmallestRatio")
        lines.append(
            f"| {run['experiment']} {run['createdAt'][:10]} | "
            + " | ".join(str(counts["total"][label]) for label in CORE_SIGN_LABELS)
            + f" | {ratio if ratio is not None else 'n/a'} |"
        )

    gaps = sorted({gap for run in runs for gap in run.get("aslCitizenGaps", [])})
    if gaps:
        lines += ["", f"Signs with no ASL Citizen clips: {', '.join(gaps)}."]

    if any("asl-citizen" in run["trainSources"] or run["testSets"].get(ASL_TEST) for run in runs):
        lines += ["", CITATION]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Regenerate docs/SIGN_RESULTS.md.")
    parser.add_argument("--reports-dir", type=Path, default=REPORTS_DIR)
    parser.add_argument("--output", type=Path, default=RESULTS_DOC_PATH)
    args = parser.parse_args()
    runs = load_runs(args.reports_dir)
    args.output.write_text(render(runs), encoding="utf-8")
    print(f"Wrote {args.output} from {len(runs)} runs.")


if __name__ == "__main__":
    main()
